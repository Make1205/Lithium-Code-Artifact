/* (p * x) >> 51 for p, x < 2^52, approximated as 2*floor(p*x / 2^52) =
 * madd52hi << 1 -- i.e. we keep ONLY the high 52-bit product and drop the
 * bit-51 carry of the low product.  That truncation is <= 1 ULP(Q51) per
 * multiply; over the degree-5 Horner + table scale it costs ~0.4 bits, so
 * the kernel still measures max rel err 2^-48.2 over [0, a_max] (>5 bits
 * past the 2^-43 IRS gate; mirrored + re-asserted by
 * tools/avxexp/gen_avxexp_ifma_consts.py --check).
 *
 * Microarch note (measurements on one i7-11700K test system showed one
 * 512-bit IFMA unit on port 0; vpmadd52 AND every vector shift issue 1/cyc
 * on p0 and CONTEND -- see tools/uarch/RESULTS.md): this halves mulsh52's
 * port-0 footprint from {2 vpmadd52 + 2 shift} to {1 vpmadd52hi + 1
 * vpsllq}, the kernel's dominant cost.  The dropped vpord was already free
 * (p0/p5). */
static inline __m512i mulsh52(__m512i p, __m512i x)
{
    __m512i hi = _mm512_madd52hi_epu64(_mm512_setzero_si512(), p, x);
    return _mm512_slli_epi64(hi, 1);
}

/* 8 lanes: a_q60 (Q60 uint64) -> exp_q63 (Q63 uint64). */
static inline __m512i exp_ifma_q63x8(__m512i aq60)
{
    const __m512d INV = _mm512_set1_pd(APPROX_EXP_IFMA_INV); /* 32/ln2 */
    const __m512d LB = _mm512_set1_pd(APPROX_EXP_IFMA_LB);   /* ln2/32 */
    const __m512d SCQ = _mm512_set1_pd(APPROX_EXP_IFMA_SCQ); /* 2^51   */
    const __m512d INV60 =
        _mm512_set1_pd(APPROX_EXP_IFMA_INV60); /* 2^-60 */

    /* a = a_q60 * 2^-60 (the ~2^-52 rounding of cvtepu64_pd is far below
     * the 2^-43 budget). */
    __m512d va = _mm512_mul_pd(_mm512_cvtepu64_pd(aq60), INV60);
    /* m = ceil(a * 32/ln2) + 31 (range reduction; multiply, no divide). */
    __m512d md = _mm512_add_pd(_mm512_ceil_pd(_mm512_mul_pd(va, INV)),
                               _mm512_set1_pd(31.0));
    __m512i m = _mm512_cvtpd_epi64(md);
    __m512i n = _mm512_srli_epi64(m, 5);
    __m512i j = _mm512_and_si512(m, _mm512_set1_epi64(31));
    __m512d rl = _mm512_fmsub_pd(md, LB, va); /* r_l in [31/32 ln2, ln2) */
    __m512i X =
        _mm512_cvtpd_epi64(_mm512_mul_pd(rl, SCQ)); /* r_l in Q51 */

    /* degree-5 Q51 Horner: p ~ exp(r_l), value in [1,2)*2^51. */
    __m512i p = _mm512_set1_epi64((long long)POLY_C_Q51[5]);
    for (int i = 4; i >= 0; i--)
        p = _mm512_add_epi64(mulsh52(p, X),
                             _mm512_set1_epi64((long long)POLY_C_Q51[i]));

    /* constant-time table lookup s = TAB_Q51[j], j in [0,31]: TWO vpermt2q
     * register permutes over the 4 zmm holding the 32 entries, blended by
     * bit 4 of j -- ~4 ops vs the old 64-op (32x cmp+blend) linear scan.
     * vpermt2q is a register shuffle (data-independent timing, NOT a
     * memory gather), and j is public-range, so this stays constant-time.
     */
    const __m512i T0 = _mm512_loadu_si512((const __m512i *)(TAB_Q51 + 0));
    const __m512i T1 = _mm512_loadu_si512((const __m512i *)(TAB_Q51 + 8));
    const __m512i T2 = _mm512_loadu_si512((const __m512i *)(TAB_Q51 + 16));
    const __m512i T3 = _mm512_loadu_si512((const __m512i *)(TAB_Q51 + 24));
    __m512i s = _mm512_mask_blend_epi64(
        _mm512_test_epi64_mask(j, _mm512_set1_epi64(16)),
        _mm512_permutex2var_epi64(T0, j, T1),  /* TAB[j&15]      (j<16) */
        _mm512_permutex2var_epi64(T2, j, T3)); /* TAB[16+(j&15)] (j>=16) */
    __m512i ps = mulsh52(p, s); /* 2^{-j/32} exp(r_l), Q51, [2^51, 2^52) */

    /* exp_q63 = ps << (12 - n).  Exact and TOTAL over the whole sampler
     * domain: the consts gate asserts max n = 11, so e = 12 - n is always
     * in [1, 12] >= 0 and a left shift only appends zero bits.  Wider
     * shift-right/zero handling is unnecessary for valid sampler inputs,
     * which keeps this hot path smaller and cheaper. */
    __m512i e = _mm512_sub_epi64(_mm512_set1_epi64(12), n); /* 12 - n */
    return _mm512_sllv_epi64(ps, e);
}

void approx_exp_avx512ifma(uint64_t *expv, const uint64_t *a_q60, int n)
{
    int i = 0;
    for (; i + 8 <= n; i += 8) {
        __m512i aq = _mm512_loadu_si512((const __m512i *)(a_q60 + i));
        _mm512_storeu_si512((__m512i *)(expv + i), exp_ifma_q63x8(aq));
    }
    /* scalar tail (GAUSS_BATCH=32 is a multiple of 8, so normally none).
     */
    for (; i < n; i++)
        expv[i] = approx_exp(a_q60[i]);
}
