#!/usr/bin/env python3
"""Offline generator for IRS NTT zeta tables and Montgomery constants.

Patches the NTT constants block in ref/ntt.h.

Three parameter sets (see docs/design-notes/param.md):

  Lithium-120 : (q=57601, n=256, base_deg=2)  incomplete NTT, rho is N-th root
  Lithium-180 : (q=30977, n=256, base_deg=2)  incomplete NTT, rho is N-th root
  Lithium-260 : (q=64513, n=512, base_deg=1)  full NTT,        rho is 2N-th root

NTT-friendliness (the reason for the split):
  q-1 = 2^v2 * odd. Full negacyclic NTT needs 2N | q-1; incomplete (Kyber-style,
  base-case deg 2) only needs N | q-1.
    57601-1 = 2^8 * 225   -> 256 | q-1 but 512 not | q-1  -> base_deg=2
    30977-1 = 2^8 * 121   -> 256 | q-1 but 512 not | q-1  -> base_deg=2
    64513-1 = 2^10 * 63   -> 1024 | q-1                   -> base_deg=1 (n=512)

Layout (matches ntt.c, Kyber-style unsigned uint16 Montgomery):
  - uint16_t coefficients in [0,q), R = 2^16 Montgomery base (AVX2 16-bit lanes).
  - zetas[i] = MONT * rho^{bitrev(i, log2(zetas_size))} mod q, unsigned [0,q).
  - zetas_size = N for full NTT, N/2 for incomplete NTT.
  - butterflies consume zetas[1..zetas_size-1]; for base_deg=2 the basemul over
    Z_q[X]/(X^2 - zeta_i) reuses zetas[zetas_size/2 .. zetas_size-1] (+/- pairs,
    negation done as q-zeta in uint16).

Per the project "Python full-reproduction" principle this script PRINTS the full
derivation of every emitted constant.

Run:  python3 gen_zetas.py
"""

import os
import autogen

# ============================================================
# Math utilities
# ============================================================

def factorize(n):
    factors = []
    d = 2
    while d * d <= n:
        if n % d == 0:
            factors.append(d)
            while n % d == 0:
                n //= d
        d += 1
    if n > 1:
        factors.append(n)
    return factors


def mod_order(g, q):
    n = q - 1
    for p in factorize(n):
        while n % p == 0 and pow(g, n // p, q) == 1:
            n //= p
    return n


def primitive_root(q, order_want):
    for g in range(2, q):
        if mod_order(g, q) == order_want:
            return g
    raise ValueError(f"No element of order {order_want} mod {q}")


def bitrev(x, bits):
    r = 0
    for i in range(bits):
        r = (r << 1) | ((x >> i) & 1)
    return r


def signed(x, q):
    x %= q
    if x > q // 2:
        x -= q
    return x


def v2(n):
    k = 0
    while n % 2 == 0 and n > 0:
        n //= 2
        k += 1
    return k


# ============================================================
# Per-mode generator
# ============================================================

def gen(q, N, base_deg):
    """NTT constants for ring Z_q[X]/(X^N+1) with given base degree.

    base_deg=1: full NTT      (requires q == 1 mod 2N).
    base_deg=2: incomplete    (requires q == 1 mod N).
    """
    assert base_deg in (1, 2)

    MONT = pow(2, 16, q)                 # R = 2^16 mod q (uint16 Montgomery base)
    QINV = (-pow(q, -1, 1 << 16)) % (1 << 16)   # -q^{-1} mod 2^16, for the +m*q reduce
    V = round((1 << 16) / q)            # Barrett placeholder (AVX2 path refines precision)

    if base_deg == 1:
        rho_order = 2 * N
        zetas_size = N
    else:
        rho_order = N
        zetas_size = N // 2

    if (q - 1) % rho_order != 0:
        raise ValueError(
            f"q={q}: no primitive {rho_order}-th root (q-1={q-1}, v2={v2(q-1)}, "
            f"need >= log2({rho_order})={rho_order.bit_length()-1}).")

    rho = primitive_root(q, rho_order)
    bits = zetas_size.bit_length() - 1
    # unsigned [0,q) Montgomery-domain twiddles: zeta_i = rho^bitrev(i) * R mod q
    zetas = [(MONT * pow(rho, bitrev(i, bits), q)) % q
             for i in range(zetas_size)]
    # final invntt scale fuses R^2 (mont^2) so basemul's owed R is paid back and
    # products land in normal domain; size = N (full) / N/2 (incomplete) = 2^levels.
    invntt_f = (MONT * MONT * pow(zetas_size, -1, q)) % q

    return dict(q=q, N=N, base_deg=base_deg, MONT=MONT, QINV=QINV, BARRETT_V=V,
                rho=rho, rho_order=rho_order, zetas=zetas, zetas_size=zetas_size,
                invntt_f=invntt_f)


def fmt_zetas_table(zetas, indent="    "):
    out = []
    for i in range(0, len(zetas), 8):
        out.append(indent + ", ".join(f"{v:5d}" for v in zetas[i:i+8]) + ",")
    return "\n".join(out)


HEADER_TEMPLATE = '''\
/*
 * ntt.h generated block - per-mode NTT / Montgomery constants for IRS.
 *
 * AUTO-GENERATED by tools/gen_zetas.py. DO NOT EDIT BY HAND.
 *
{mode_summary}
 *
 * R = 2^16 Montgomery base (uint16 NTT engine; AVX2-aligned 16-bit lanes).
 *
 * MONT      = 2^16 mod q.
 * QINV      = -q^{{-1}} mod 2^16   (paired with the +m*q reduce in reduce.c).
 * BARRETT_V = round(2^16 / q)   (placeholder; AVX2 Barrett refines precision).
 * INVNTT_F  = MONT^2 / zetas_size mod q  --  final invntt scale (fuses R^2;
 *             pays back the R that basemul/pointwise owe -> products normal domain).
 * zetas/INVNTT_F are unsigned in [0,q) (q can exceed 2^15; read as uint16).
 */

#ifndef LITHIUM_NTT_CONSTANTS_H
#define LITHIUM_NTT_CONSTANTS_H

#include <stdint.h>
#include "config.h"

{mode_blocks}

#endif /* LITHIUM_NTT_CONSTANTS_H */
'''

MODE_BLOCK_TEMPLATE = '''\
/* ============================================================
 * IRS-{security} : q = {q}, n = {N}, base_deg = {base_deg}
 *   primitive {rho_order}-th root of unity: rho = {rho}
 * ============================================================ */
#if LITHIUM_MODE == {security}

#define MONT           {MONT}U
#define QINV           {QINV}U
#define BARRETT_V      {BARRETT_V}
#define INVNTT_F       {invntt_f}U
#define NTT_ZETAS_SIZE {zetas_size}

static const uint16_t zetas[NTT_ZETAS_SIZE] = {{
{zetas_table}
}};

#endif /* LITHIUM_MODE == {security} */
'''


def main():
    modes = [
        ("120", 57601, 256, 2),
        ("180", 30977, 256, 2),
        ("260", 64513, 512, 1),
    ]

    results, summary_lines, blocks = [], [], []
    print("=" * 64)
    print("IRS gen_zetas.py  --  derivation of every emitted constant")
    print("=" * 64)
    for security, q, N, base_deg in modes:
        r = gen(q, N, base_deg)
        results.append((security, r))
        kind = "full NTT" if base_deg == 1 else "incomplete NTT (basecase deg 2)"
        summary_lines.append(
            f" *   IRS-{security} : q={r['q']}, n={r['N']}, rho={r['rho']} "
            f"(order {r['rho_order']}), {kind}")
        # ---- printed derivation (Python full-reproduction principle) ----
        print(f"\n--- IRS-{security} : q={q}, n={N}, base_deg={base_deg} "
              f"({kind}) ---")
        print(f"  q-1 = {q-1} = 2^{v2(q-1)} * {(q-1)>>v2(q-1)}")
        print(f"  rho_order = {r['rho_order']}  (need {r['rho_order']} | q-1: "
              f"{(q-1) % r['rho_order'] == 0})")
        print(f"  rho (smallest primitive {r['rho_order']}-th root) = {r['rho']}")
        print(f"  MONT = 2^16 mod q       = {r['MONT']}")
        print(f"  QINV = -q^-1 mod 2^16   = {r['QINV']} (0x{r['QINV']:04X})")
        print(f"  BARRETT_V = round(2^16/q) = {r['BARRETT_V']}")
        print(f"  zetas_size = {r['zetas_size']}  (= N for full, N/2 for incomplete)")
        print(f"  INVNTT_F = MONT^2 / zetas_size mod q = {r['invntt_f']}")
        print(f"  zetas[0..3] = {r['zetas'][:4]}  ... zetas[-2:] = {r['zetas'][-2:]}")
        blocks.append(MODE_BLOCK_TEMPLATE.format(
            security=security, q=r["q"], N=r["N"], base_deg=r["base_deg"],
            rho=r["rho"], rho_order=r["rho_order"], MONT=r["MONT"], QINV=r["QINV"],
            BARRETT_V=r["BARRETT_V"], invntt_f=r["invntt_f"],
            zetas_size=r["zetas_size"], zetas_table=fmt_zetas_table(r["zetas"])))

    body = ("/* Per-mode NTT / Montgomery constants (R = 2^16; see tools/gen_zetas.py).\n"
            + "\n".join(summary_lines) + "\n */\n"
            + "\n".join(blocks))
    here = os.path.dirname(os.path.abspath(__file__))
    out_path = os.path.normpath(os.path.join(here, "..", "ref", "ntt.h"))
    autogen.patch_region(out_path, "ntt", body)
    print(f"\nPatched @@AUTOGEN:ntt@@ region in {out_path}")


if __name__ == "__main__":
    main()
